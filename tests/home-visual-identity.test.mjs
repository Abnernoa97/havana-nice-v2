import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
test('PWA HOME uses a scoped lightweight emerald-gold theme without affecting Chat or BOOK',()=>{
 const css=read('apps/pwa/src/styles/home/home.css');
 assert.match(css,/\.visual-shell\{--hn-forest:#133B30;--hn-deep:#0D2A23;/);
 assert.match(css,/--hn-gold:#B69358;--hn-gold-light:#DBC59A/);
 assert.match(css,/\.visual-header\{[^\n]*background:var\(--hn-deep\)/);
 assert.match(css,/\.visual-tile:focus-visible/);
 assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
 assert.doesNotMatch(css,/(?:^|\n):root\{/,'HOME theme must not change Chat CSS root tokens');
 const app=read('apps/pwa/src/app/VisualApp.tsx');
 const home=read('apps/pwa/src/features/home/MemberHome.tsx');
 assert.match(app,/const MemberHome=lazy\(\(\)=>import\('\.\.\/features\/home\/MemberHome'\)\)/);
 assert.match(home,/className="hn-home-stage"/);
 assert.doesNotMatch(home,/hn-home-blank/);
 assert.doesNotMatch(read('apps/pwa/src/features/home/home-stage.css'),/hn-home-blank|height:55vh/);
 assert.match(home,/<MemberStories token=\{token\}/);
 assert.doesNotMatch(home,/visual-welcome|visual-grid|Todo lo que necesitas/);
 const strip=read('apps/pwa/src/features/home/TeamStoriesStrip.tsx');
 assert.match(strip,/person.photoUrl/);
 assert.match(strip,/onAddStory/);
 assert.match(strip,/onOpenStory/);
 assert.doesNotMatch(strip,/onOpenProfile|choosePhoto/,'Publishing a story must not enter the Profile editor');
 assert.match(app,/MemberProfilePanel/);
 const profileCSS=read('apps/pwa/src/features/profile/profile.css');
 const stageCSS=read('apps/pwa/src/features/home/home-stage.css');
 assert.match(profileCSS,/\.visual-account\{display:flex;align-items:center/);
 assert.match(profileCSS,/\.visual-account-avatar\{display:grid;place-items:center/);
 assert.match(profileCSS,/\.visual-account-label\{color:#f5f1e8/);
 assert.doesNotMatch(profileCSS,/\.hn-moment-/,'Story circle styles belong to HOME, never Profile');
 assert.doesNotMatch(profileCSS,/\.visual-bottom-nav/,
  'Bottom navigation belongs to the shell, not Profile');
 assert.match(css,/\.visual-shell:not\(\.hn-admin-editorial\) \.visual-bottom-nav button\{font-size:9px\}/);
 assert.match(css,/\.visual-shell:not\(\.hn-admin-editorial\) \.visual-bottom-nav button small\{letter-spacing:-\.025em\}/);
 assert.match(stageCSS,/\.hn-moment-circle\{appearance:none;box-sizing:border-box;overflow:visible/);
 assert.match(stageCSS,/\.hn-moment-photo img\{display:block;width:100%;height:100%/);
 assert.doesNotMatch(stageCSS,/\.visual-account(?:-avatar|-label)?\{/,
  'Shared header belongs to Profile, not the lazy HOME Story module');
 assert.match(app,/aria-current=\{screen===item.id\?'page':undefined\}/);
 assert.doesNotMatch(app+'\n'+home,/new WebSocket|startNamedChatSession|uploadChatMediaBatch/);
});
test('Android HOME presentation keeps one session and direct native modules',()=>{
 const app=read('apps/android/app/NativeMemberHome.tsx');
 assert.match(app,/backgroundColor:'#0D2A23'/);
 assert.match(app,/color:'#DBC59A'/);
 assert.match(app,/active==='family'[\s\S]*?familyViewport/);
 assert.match(app,/active==='calendar'\?<NativeCalendar token=\{token\}/);
 assert.match(app,/onPress=\{\(\)=>onNavigate\(dest\)\}/);
 assert.match(app,/useNativeMemberProfile\(token,actorId,true\)/);
 assert.match(app,/NativeStories token=\{token\}/);
 assert.doesNotMatch(app,/new WebSocket|startNamedChatSession|WebView|AsyncStorage/);
});
